// ── Lê contratos-porto.txt ─────────────────────────────────────────────────────
const txtPath = path.join(__dirname, 'contratos-porto.txt');
const lines   = fs.readFileSync(txtPath, 'utf8').split('\n');
const hdr     = lines[0].split('\t').map(h => h.trim());
const iCliente  = hdr.indexOf('CLIENTE');
const iApolice  = hdr.indexOf('APÓLICE');
const iInicio   = hdr.indexOf('INÍCIO DE VIGÊNCIA');
const iParcelas = hdr.indexOf('QUANTIDADE DE PARCELAS');
const iPremio   = hdr.indexOf('PRÊMIO');

function parseBRDate(s) {
  const p = String(s || '').trim().split('/').map(Number);
  if (p.length !== 3 || !p[0]) return null;
  return new Date(Date.UTC(p[2], p[1]-1, p[0]));
}
function parseBRNum(s) { return parseFloat(String(s||'').replace(/\./g,'').replace(',','.')) || 0; }
function addMonths(d, n) { return new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth()+n, 1)); }
function mk(d) { return `${d.getUTCFullYear()}-${String(d.getUTCMonth()+1).padStart(2,'0')}`; }

const txtMap = {}; // apolice → {cliente, inicio, parcelas, premio}
for (let i = 1; i < lines.length; i++) {
  const cols = lines[i].split('\t').map(c => c.trim());
  if (cols.length < 5) continue;
  const ap = (cols[iApolice]||'').replace(/^0+/,'');
  if (!ap) continue;
  const inicio = parseBRDate(cols[iInicio]);
  if (!inicio) continue;
  txtMap[ap] = {
    cliente:   cols[iCliente],
    inicio,
    parcelas:  parseBRNum(cols[iParcelas]),
    premio:    parseBRNum(cols[iPremio]),
  };
}

// ── Agrupa pagamentos por apólice ──────────────────────────────────────────────
const byAp = {}; // apolice → { mes → [valores] }
for (const [mes, ap, comm] of PAG) {
  const apN = ap.replace(/^0+/,'');
  if (!byAp[apN]) byAp[apN] = {};
  if (!byAp[apN][mes]) byAp[apN][mes] = [];
  byAp[apN][mes].push(comm);
}

const NET = 1 - 0.084 - 0.069;

// ── Para cada apólice: calcula commMensal padrão ───────────────────────────────
// "padrão" = menor valor de um único pagamento no mês (meses com 1 entrada = regular)
// meses com múltiplas entradas = catch-up (pagar 2+ meses ao mesmo tempo)
const resultado = {};

for (const [ap, meses] of Object.entries(byAp)) {
  const txt = txtMap[ap];

  // Pega meses com UMA ÚNICA entrada (pagamento normal, não catch-up)
  const valoresNormais = [];
  const todosValores   = [];
  for (const [mes, vals] of Object.entries(meses)) {
    const uniq = [...new Set(vals.map(v => Math.round(v*100)/100))];
    todosValores.push(...vals);
    if (uniq.length === 1) valoresNormais.push(uniq[0]);
  }

  // Comissão padrão = mediana dos meses normais; fallback = min de todos
  valoresNormais.sort((a,b) => a-b);
  const commBase = valoresNormais.length > 0
    ? valoresNormais[Math.floor(valoresNormais.length/2)]
    : Math.min(...todosValores);

  const mesList   = Object.keys(meses).sort();
  const firstMes  = mesList[0];
  const lastMes   = mesList[mesList.length-1];

  // nMeses real = premio * 4% / commBase (bruta, antes NET_FACTOR)
  let nMesesReal = null;
  if (txt && txt.premio > 0 && commBase > 0) {
    const commBruta = commBase / NET; // desfaz o NET_FACTOR para pegar bruta
    nMesesReal = Math.round((txt.premio * 0.04) / commBruta);
    if (nMesesReal < 1 || nMesesReal > 60) nMesesReal = null;
  }

  // nMeses que o sistema usa hoje
  const nMesSistema = txt
    ? ((txt.parcelas >= 1 && txt.parcelas <= 12) ? Math.round(txt.parcelas) : 12)
    : 12;

  resultado[ap] = {
    cliente:      txt?.cliente || mesList[0],
    commBase,
    firstMes,
    lastMes,
    nMesesReal,
    nMesSistema,
    premio:       txt?.premio || 0,
    inicio:       txt ? mk(txt.inicio) : null,
    mesesPagos:   mesList.length,
  };
}

